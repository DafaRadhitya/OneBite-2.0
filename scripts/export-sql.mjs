// Generates db/onebite.sql (MySQL / MariaDB, for phpMyAdmin → Import) from the app's JSON data.
// Run: pnpm export:sql
// The JSON files stay the source of truth until the app actually reads from the database.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'

const dishes = JSON.parse(readFileSync(new URL('../src/data/dishes.json', import.meta.url)))
const { meta, restaurants } = JSON.parse(readFileSync(new URL('../src/data/restaurants.json', import.meta.url)))

const q = (v) => (v === null || v === undefined ? 'NULL' : `'${String(v).replace(/\\/g, '\\\\').replace(/'/g, "''")}'`)
const b = (v) => (v ? 1 : 0)
const t = (hhmm) => q(`${hhmm}:00`)

const out = []
const L = (s = '') => out.push(s)

L('-- OneBite database — generated by scripts/export-sql.mjs. Do not edit by hand; edit src/data/*.json and re-run.')
L(`-- Area: ${meta.area}`)
if (meta.sample) L('-- WARNING: SAMPLE DATA. Places, coordinates, hours and prices are illustrative, not real businesses.')
L()
L('SET NAMES utf8mb4;')
L('SET FOREIGN_KEY_CHECKS = 0;')
L('DROP VIEW IF EXISTS v_dish_places;')
L('DROP TABLE IF EXISTS menu_items, dish_pitches, dish_best_times, restaurants, dishes;')
L('SET FOREIGN_KEY_CHECKS = 1;')
L()
L(`CREATE TABLE dishes (
  id         VARCHAR(50)  NOT NULL PRIMARY KEY,           -- e.g. 'nasi-goreng' (also used in app URLs)
  name       VARCHAR(100) NOT NULL,
  emoji      VARCHAR(16)  NOT NULL,
  cuisine    VARCHAR(50)  NOT NULL,
  spicy      TINYINT UNSIGNED NOT NULL DEFAULT 0,          -- 0 not spicy … 3 very spicy
  sweet      BOOLEAN NOT NULL DEFAULT FALSE,
  soupy      BOOLEAN NOT NULL DEFAULT FALSE,
  heaviness  ENUM('light','medium','heavy') NOT NULL,
  CONSTRAINT chk_dish_spicy CHECK (spicy BETWEEN 0 AND 3)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;`)
L()
L(`CREATE TABLE dish_best_times (
  dish_id    VARCHAR(50) NOT NULL,
  meal_time  ENUM('breakfast','lunch','dinner','late') NOT NULL,
  PRIMARY KEY (dish_id, meal_time),
  CONSTRAINT fk_besttime_dish FOREIGN KEY (dish_id) REFERENCES dishes(id) ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;`)
L()
L(`CREATE TABLE dish_pitches (
  id         INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  dish_id    VARCHAR(50) NOT NULL,
  pitch      VARCHAR(255) NOT NULL,                        -- the "convince me" line
  sort_order TINYINT UNSIGNED NOT NULL DEFAULT 0,
  CONSTRAINT fk_pitch_dish FOREIGN KEY (dish_id) REFERENCES dishes(id) ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;`)
L()
L(`CREATE TABLE restaurants (
  id          VARCHAR(60)  NOT NULL PRIMARY KEY,
  name        VARCHAR(120) NOT NULL,
  area        VARCHAR(60)  NOT NULL,
  lat         DECIMAL(9,6) NOT NULL,
  lng         DECIMAL(9,6) NOT NULL,
  open_time   TIME NOT NULL,                               -- close_time < open_time means it closes after midnight
  close_time  TIME NOT NULL,                               -- '00:00:00'-'24:00:00' means open 24 hours
  is_sample   BOOLEAN NOT NULL DEFAULT TRUE,               -- set FALSE only for real, verified places
  INDEX idx_restaurants_area (area)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;`)
L()
L(`CREATE TABLE menu_items (
  id            INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  restaurant_id VARCHAR(60)  NOT NULL,
  name          VARCHAR(120) NOT NULL,
  price         INT UNSIGNED NOT NULL,                     -- whole Rupiah, e.g. 15000
  dish_id       VARCHAR(50)  NULL,                         -- NULL = on the menu but never rolled (drinks, sides)
  sort_order    SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  INDEX idx_menu_dish (dish_id),
  CONSTRAINT fk_menu_restaurant FOREIGN KEY (restaurant_id) REFERENCES restaurants(id) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT fk_menu_dish FOREIGN KEY (dish_id) REFERENCES dishes(id) ON DELETE SET NULL ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;`)
L()

L('-- ── dishes ─────────────────────────────────────────────')
L('INSERT INTO dishes (id, name, emoji, cuisine, spicy, sweet, soupy, heaviness) VALUES')
L(dishes.map((d) => `  (${[q(d.id), q(d.name), q(d.emoji), q(d.cuisine), d.spicy, b(d.sweet), b(d.soupy), q(d.heaviness)].join(', ')})`).join(',\n') + ';')
L()
L('INSERT INTO dish_best_times (dish_id, meal_time) VALUES')
L(dishes.flatMap((d) => d.bestTimes.map((m) => `  (${q(d.id)}, ${q(m)})`)).join(',\n') + ';')
L()
L('INSERT INTO dish_pitches (dish_id, pitch, sort_order) VALUES')
L(dishes.flatMap((d) => d.pitches.map((p, i) => `  (${q(d.id)}, ${q(p)}, ${i})`)).join(',\n') + ';')
L()

L('-- ── restaurants ────────────────────────────────────────')
L('INSERT INTO restaurants (id, name, area, lat, lng, open_time, close_time, is_sample) VALUES')
L(
  restaurants
    .map((r) => {
      const [o, c] = r.hours.split('-')
      return `  (${[q(r.id), q(r.name), q(r.area), r.lat.toFixed(6), r.lng.toFixed(6), t(o), t(c), b(meta.sample)].join(', ')})`
    })
    .join(',\n') + ';',
)
L()
L('INSERT INTO menu_items (restaurant_id, name, price, dish_id, sort_order) VALUES')
L(restaurants.flatMap((r) => r.menu.map((m, i) => `  (${[q(r.id), q(m.name), m.price, q(m.dishId ?? null), i].join(', ')})`)).join(',\n') + ';')
L()

L('-- ── handy view: every dish with the places that serve it ──')
L(`CREATE VIEW v_dish_places AS
SELECT d.id AS dish_id, d.name AS dish, r.id AS restaurant_id, r.name AS restaurant, r.area,
       m.name AS menu_item, m.price, r.lat, r.lng, r.open_time, r.close_time
FROM menu_items m
JOIN dishes d      ON d.id = m.dish_id
JOIN restaurants r ON r.id = m.restaurant_id;`)
L()
L(`-- Example queries:
--   Where can I get bakso, cheapest first?
--     SELECT restaurant, area, menu_item, price FROM v_dish_places WHERE dish_id = 'bakso' ORDER BY price;
--   Dishes available for 15k or less:
--     SELECT DISTINCT dish FROM v_dish_places WHERE price <= 15000 ORDER BY dish;`)

mkdirSync(new URL('../db/', import.meta.url), { recursive: true })
writeFileSync(new URL('../db/onebite.sql', import.meta.url), out.join('\n') + '\n')
const items = restaurants.reduce((n, r) => n + r.menu.length, 0)
console.log(`Wrote db/onebite.sql: ${dishes.length} dishes, ${restaurants.length} restaurants, ${items} menu items.`)
